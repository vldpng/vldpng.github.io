/**
 * Отправляет тестовое уведомление о сбое — проверка настройки алертов:
 * токен, TELEGRAM_ALERT_CHAT_ID, права бота в чате, вёрстка сообщения.
 *
 *   npm run telegram:test-alert
 *
 * Заодно показывает работу троттлинга: вторая одинаковая ошибка подряд
 * в чат не уйдёт, а будет посчитана как подавленная.
 *
 * Если TELEGRAM_ALERT_CHAT_ID не заполнен, ничего не отправляется —
 * сбой просто пишется в лог, как и в бою.
 */
import 'dotenv/config';
import { reportError } from '../src/server/alerts';

const configured = Boolean(process.env.TELEGRAM_BOT_TOKEN && process.env.TELEGRAM_ALERT_CHAT_ID);

if (!configured) {
  console.log(
    'TELEGRAM_ALERT_CHAT_ID (или токен) не заполнен — отправки не будет.\n' +
      'Сбой уйдёт только в лог, ровно как в проде с незаданной переменной.\n',
  );
}

// Настоящая ошибка со стеком: в сообщении видно и текст, и место падения.
const error = new Error('Тестовый сбой: заявка №1234 не записалась в базу');

reportError('ТЕСТ', error, {
  Телефон: '+371 20 123 456',
  Источник: 'проверка настройки алертов',
});

// Второй вызов с той же сигнатурой — должен быть подавлен троттлингом.
reportError('ТЕСТ', new Error('Тестовый сбой: заявка №5678 не записалась в базу'));

// reportError намеренно не ждёт доставки, поэтому даём запросу уйти.
await new Promise((resolve) => setTimeout(resolve, 3000));

console.log(
  configured
    ? '\nОтправлено одно сообщение — проверьте чат алертов.\n' +
        'Второй вызов подавлён троттлингом: одинаковые ошибки не чаще раза в 15 минут.'
    : '\nГотово: оба сбоя записаны в лог выше.',
);
