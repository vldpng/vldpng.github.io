/**
 * Баннеры посадочных страниц услуг.
 *
 * Один макет на все услуги — заказчик прислал скриншоты, где страницы
 * отличаются только текстом и снимком. Поэтому вёрстка живёт в одном
 * компоненте (ui/service-hero), а здесь — только содержимое.
 *
 * Ключ — слаг услуги (`id` из services.ts, он же адрес /services/<id>).
 * Услуга без записи в этом файле показывает прежнюю тёмную шапку ServicePage.
 *
 * Цены — из общего прайса клиники в евро (data/prices.ts). На макетах в этих
 * строках стояли рубли: скриншоты сделаны по чужому шаблону, и переносить
 * оттуда суммы нельзя — клиника работает в Латвии.
 */
export interface ServiceHeroContent {
  /** Заголовок H1. Обычно длиннее названия в каталоге: «… в Юрмале». */
  title: string;
  /** Синяя строка под заголовком. Есть не у всех услуг. */
  subtitle?: string;
  /** Строка с ценой или ключевым обещанием — крупнее списка. */
  lead?: string;
  bullets: string[];
  image: string;
  /** alt снимка: описывает картинку, а не повторяет заголовок. */
  imageAlt: string;
  /** Своя заливка баннера. По умолчанию — общий тёплый градиент. */
  background?: string;
  /** Заливка для телефона, если общая там плохо читается. По умолчанию — background. */
  backgroundMobile?: string;
  /** Светлый текст — для тёмных заливок. */
  tone?: 'dark' | 'light';
}

