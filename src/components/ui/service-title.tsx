import React from 'react';

/** Город, который всегда уносится на отдельную строку. */
const CITY = 'Юрмале';

interface ServiceTitleProps {
  title: string;
  /** Классы самого h1 — у баннеров они разные. */
  className?: string;
}

/**
 * Заголовок посадочной страницы услуги.
 *
 * Название города всегда стоит отдельной строкой: «Лечение на элайнерах в /
 * Юрмале». Само по себе оно так не переносится — где именно ляжет перенос,
 * решает ширина колонки, и на разных страницах строка рвалась в разных
 * местах.
 *
 * Перенос сделан блочным span, а не <br> и не двумя заголовками: текст
 * остаётся одним h1 — цельным и для поиска, и для скринридера, — а разрыв
 * при этом не зависит от ширины контейнера.
 *
 * Заголовок без города (если такой появится) выводится как есть.
 */
export function ServiceTitle({ title, className }: ServiceTitleProps) {
  const at = title.lastIndexOf(` ${CITY}`);

  if (at === -1) return <h1 className={className}>{title}</h1>;

  // Пробел перед городом остаётся в первой части, а не съедается разрывом:
  // иначе в textContent слова слипались в «вЮрмале» — так заголовок читал бы
  // скринридер и так он попадал бы в буфер при копировании. На вид пробел
  // не виден, концевые пробелы строки при отрисовке схлопываются.
  return (
    <h1 className={className}>
      {title.slice(0, at + 1)}
      <span className="block">{title.slice(at + 1)}</span>
    </h1>
  );
}
