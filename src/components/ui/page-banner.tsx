import React from 'react';

interface PageBannerProps {
  /** Заголовок страницы (h1), выводится по центру над контентом. */
  title: string;
}

/**
 * Заголовок внутренней страницы — визуально скрыт.
 *
 * Крупную надпись над контентом убрали со всех страниц, но сам h1 оставлен
 * в разметке: без него у страницы нет заголовка первого уровня ни для
 * поисковой выдачи, ни для скринридера. Формулировки развёрнутые
 * («Цены в клинике RoyalDent») — они соответствуют содержимому страницы,
 * так что это обычный скрытый заголовок, а не текст для поисковиков.
 */
export function PageBanner({ title }: PageBannerProps) {
  return <h1 className="sr-only">{title}</h1>;
}
