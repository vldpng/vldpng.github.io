/**
 * Каталоги, в которые сервер пишет во время работы.
 *
 * Их два — база и загруженные через панель фото сотрудников, — и оба обязаны
 * лежать ВНЕ каталога приложения: деплой подменяет папку с кодом целиком,
 * и всё, что оказалось внутри, он унесёт. Для базы это заявки, для фото —
 * снимки врачей, на которые уже ссылаются записи в этой самой базе.
 *
 * Путь берём из DB_DIR: на проде переменная обязательна (см. env.ts), поэтому
 * расположение там всегда задано явно. Считать от process.cwd() нельзя —
 * под Phusion Passenger рабочий каталог задаёт он, и совпадать с каталогом
 * приложения не обязан.
 *
 * Ровно на этом и ломалась загрузка фото: admin.ts писал файл относительно
 * cwd, а server.ts раздавал его относительно каталога server.cjs. В dev оба
 * пути совпадают, поэтому расхождение было незаметным. Теперь каталог
 * вычисляется здесь один раз, и разойтись им негде.
 */
import { mkdirSync } from 'node:fs';
import path from 'node:path';

/** Постоянный каталог приложения: база и всё, что загружается во время работы. */
export const DATA_DIR = process.env.DB_DIR || path.join(process.cwd(), 'storage');

/** Фото сотрудников, загруженные через панель администратора. */
export const UPLOADS_STAFF_DIR = path.join(DATA_DIR, 'uploads', 'staff');

mkdirSync(UPLOADS_STAFF_DIR, { recursive: true });
